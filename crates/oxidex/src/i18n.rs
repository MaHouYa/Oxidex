#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn system_locale_resolves_chinese_to_zh_cn() {
        assert_eq!(
            resolve_language(LanguageMode::System, Some("zh_CN.UTF-8")),
            ResolvedLanguage::ZhCn
        );
        assert_eq!(
            resolve_language(LanguageMode::System, Some("zh_Hans_CN")),
            ResolvedLanguage::ZhCn
        );
    }

    #[test]
    fn system_locale_resolves_english_to_en_us() {
        assert_eq!(
            resolve_language(LanguageMode::System, Some("en_US.UTF-8")),
            ResolvedLanguage::EnUs
        );
    }

    #[test]
    fn explicit_language_overrides_system_locale() {
        assert_eq!(
            resolve_language(LanguageMode::EnUs, Some("zh_CN.UTF-8")),
            ResolvedLanguage::EnUs
        );
        assert_eq!(
            resolve_language(LanguageMode::ZhCn, Some("en_US.UTF-8")),
            ResolvedLanguage::ZhCn
        );
    }

    #[test]
    fn all_text_keys_have_english_and_chinese_text() {
        for key in ALL_TEXT_KEYS {
            assert!(!tr(ResolvedLanguage::EnUs, *key).trim().is_empty());
            assert!(!tr(ResolvedLanguage::ZhCn, *key).trim().is_empty());
        }
    }
}
