pub fn resolve_language(mode: LanguageMode, sys_locale: Option<&str>) -> ResolvedLanguage {
    match mode {
        LanguageMode::EnUs => ResolvedLanguage::EnUs,
        LanguageMode::ZhCn => ResolvedLanguage::ZhCn,
        LanguageMode::System => {
            let locale = sys_locale.unwrap_or_default().to_ascii_lowercase();
            let locale = locale.replace('-', "_");
            if locale.starts_with("zh") {
                ResolvedLanguage::ZhCn
            } else {
                ResolvedLanguage::EnUs
            }
        }
    }
}

pub fn system_language(mode: LanguageMode) -> ResolvedLanguage {
    let locale = sys_locale::get_locale();
    resolve_language(mode, locale.as_deref())
}

pub fn language_mode_value(mode: LanguageMode) -> &'static str {
    match mode {
        LanguageMode::System => "system",
        LanguageMode::EnUs => "en_us",
        LanguageMode::ZhCn => "zh_cn",
    }
}

pub fn tr(language: ResolvedLanguage, key: Text) -> &'static str {
    match language {
        ResolvedLanguage::EnUs => en_us(key),
        ResolvedLanguage::ZhCn => zh_cn(key),
    }
}

